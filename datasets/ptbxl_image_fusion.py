from pathlib import Path

import pandas as pd
from PIL import Image
from torch.utils.data import Dataset
from torchvision import transforms

from .ptbxl import PTBXLClassificationDataset


class PTBXLImageFusionDataset(Dataset):
    """
    Wrap PTBXLClassificationDataset and attach the corresponding
    pre-rendered ECG image from:

        data/ptbxl_images/<split>/manifest.csv

    Each returned sample keeps the original PTB-XL waveform fields and adds:

        sample["x_image"] -> FloatTensor [3, 224, 224]

    The wrapper also exposes metadata/attributes from the underlying
    PTBXLClassificationDataset so existing MedTsLLM/trainer code can use it
    as if it were the original PTB-XL dataset.
    """

    supported_tasks = ["classification"]

    def __init__(self, config, split="train"):
        super().__init__()

        self.split = split
        self.config = config

        # Existing waveform dataset used by MedTsLLM.
        self.waveform_ds = PTBXLClassificationDataset(
            config,
            split=split,
        )

        # Explicitly mirror important metadata expected by MedTsLLM/trainer.
        # __getattr__ below forwards any additional attributes automatically.
        if hasattr(self.waveform_ds, "n_classes"):
            self.n_classes = self.waveform_ds.n_classes

        if hasattr(self.waveform_ds, "class_names"):
            self.class_names = self.waveform_ds.class_names

        if hasattr(self.waveform_ds, "classes"):
            self.classes = self.waveform_ds.classes

        if hasattr(self.waveform_ds, "seq_len"):
            self.seq_len = self.waveform_ds.seq_len

        if hasattr(self.waveform_ds, "n_channels"):
            self.n_channels = self.waveform_ds.n_channels

        if hasattr(self.waveform_ds, "features"):
            self.features = self.waveform_ds.features

        if hasattr(self.waveform_ds, "labels"):
            self.labels = self.waveform_ds.labels

        # Manifest generated by prepare_ptbxl_images.py.
        manifest_path = (
            Path("data")
            / "ptbxl_images"
            / split
            / "manifest.csv"
        )

        if not manifest_path.exists():
            raise FileNotFoundError(
                f"Missing image manifest: {manifest_path}. "
                "Run prepare_ptbxl_images.py before training."
            )

        self.manifest_path = manifest_path
        self.manifest = pd.read_csv(manifest_path)

        if len(self.manifest) != len(self.waveform_ds):
            raise RuntimeError(
                f"Waveform/image count mismatch for split={split!r}: "
                f"{len(self.waveform_ds)} waveform samples vs "
                f"{len(self.manifest)} manifest rows."
            )

        required_columns = {"path", "label"}
        missing_columns = required_columns.difference(self.manifest.columns)
        if missing_columns:
            raise RuntimeError(
                f"Manifest {manifest_path} is missing required columns: "
                f"{sorted(missing_columns)}"
            )

        # ImageNet normalization for pretrained ConvNeXt.
        self.image_transform = transforms.Compose(
            [
                transforms.Resize((224, 224)),
                transforms.ToTensor(),
                transforms.Normalize(
                    mean=[0.485, 0.456, 0.406],
                    std=[0.229, 0.224, 0.225],
                ),
            ]
        )

    def __len__(self):
        return len(self.waveform_ds)

    def __getitem__(self, idx):
        sample = self.waveform_ds[idx]

        if not isinstance(sample, dict):
            raise TypeError(
                "PTBXLClassificationDataset must return a dict for "
                "PTBXLImageFusionDataset. "
                f"Got {type(sample)!r} at index {idx}."
            )

        # Copy so we do not mutate the underlying dataset's object in-place.
        sample = dict(sample)

        row = self.manifest.iloc[idx]
        image_path = Path(str(row["path"]))

        if not image_path.is_absolute():
            # Current manifests contain paths such as:
            # data/ptbxl_images/train/0000000.png
            image_path = Path.cwd() / image_path

        if not image_path.exists():
            raise FileNotFoundError(
                f"Missing ECG image for split={self.split!r}, idx={idx}: "
                f"{image_path}"
            )

        image = Image.open(image_path).convert("RGB")
        image = self.image_transform(image)

        # Safety check: make sure the manifest label agrees with the waveform
        # dataset label whenever a scalar label is available.
        waveform_label = sample.get("labels", None)
        manifest_label = int(row["label"])

        if waveform_label is not None:
            try:
                waveform_label_int = int(waveform_label.item())
            except Exception:
                try:
                    waveform_label_int = int(waveform_label)
                except Exception:
                    waveform_label_int = None

            if (
                waveform_label_int is not None
                and waveform_label_int != manifest_label
            ):
                raise RuntimeError(
                    f"Waveform/image label mismatch at split={self.split!r}, "
                    f"idx={idx}: waveform={waveform_label_int}, "
                    f"manifest={manifest_label}."
                )

        # Hierarchical router / ConvNeXt models look for this key.
        sample["x_image"] = image

        return sample

    def __getattr__(self, name):
        """
        Forward unknown metadata/method lookups to the underlying waveform
        dataset.

        This is important because MedTsLLM and the training code may access
        attributes such as n_classes, class_names, seq_len, etc. directly on
        the dataset object.
        """
        if name == "waveform_ds":
            raise AttributeError(name)

        waveform_ds = self.__dict__.get("waveform_ds", None)

        if waveform_ds is not None and hasattr(waveform_ds, name):
            return getattr(waveform_ds, name)

        raise AttributeError(
            f"{self.__class__.__name__} has no attribute {name!r}"
        )


def ptbxl_image_fusion_datasets(config):
    """
    Convenience factory. The repository's normal dataset registry can use
    PTBXLImageFusionDataset directly for classification; this factory is kept
    for compatibility with older experimental code.
    """
    return {
        "train": PTBXLImageFusionDataset(config, split="train"),
        "val": PTBXLImageFusionDataset(config, split="val"),
        "test": PTBXLImageFusionDataset(config, split="test"),
    }
